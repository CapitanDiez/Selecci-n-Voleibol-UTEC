-- =========================
-- USUARIOS (RF-01, RF-20)
-- El login ahora lo hace Supabase Authentication (email y contraseña).
-- La tabla usuarios solo guarda el nombre y el ROL, y se relaciona por email.
-- =========================
alter table usuarios add column if not exists email varchar(100) unique;
alter table usuarios drop column if exists contrasena;

-- Poner el email de cada usuario (deben ser los MISMOS que se den de alta en Authentication)
update usuarios set email = 'felix@utectulancingo.edu.mx' where usuario = 'felix';
update usuarios set email = 'capitan@utectulancingo.edu.mx' where usuario = 'capitan';
update usuarios set email = 'coordinacion@utectulancingo.edu.mx' where usuario = 'coordinacion';

alter table usuarios alter column email set not null;

-- =========================
-- SESIONES ABIERTAS (RNT01)
-- Guarda los tokens JWT de las sesiones activas
-- =========================
create table if not exists sesiones_abiertas (
    id bigint generated by default as identity primary key,
    token text not null
);

-- =========================
-- FOTO DEL JUGADOR (RTT04)
-- Guarda solo el nombre del archivo; la imagen vive en static/fotos/
-- =========================
alter table jugadores add column if not exists foto varchar(150) not null default 'default.png';
